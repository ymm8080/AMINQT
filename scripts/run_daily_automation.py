def _run_step_with_watchdog(
    argv: list[str], fh, env: dict, timeout_s: int
) -> tuple[int, bool]:
    """Popen + ???????, ?? taskkill ????. ?? (rc, timed_out).

    ??? subprocess.run(timeout=): 08-27 ??? refresh ?? 8h+, ? 3h ??
    ??????? (??? TIMEOUT ??, ???????), ????????;
    ????? sleep ??? poll + ????, ??????????.
    """
    # Windows: CREATE_NEW_PROCESS_GROUP ????????, taskkill /T ????.
    # POSIX: start_new_session=True ?????/???, os.killpg ??????????.
    popen_kwargs: dict = {}
    if sys.platform == "win32":
        popen_kwargs["creationflags"] = subprocess.CREATE_NEW_PROCESS_GROUP
    else:
        popen_kwargs["start_new_session"] = True
    proc = subprocess.Popen(
        argv, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT, env=env, **popen_kwargs
    )
    state = {"timed_out": False}

    def _watch() -> None:
        time.sleep(timeout_s)
        if proc.poll() is None:
            state["timed_out"] = True
            _kill_tree(proc.pid)

    threading.Thread(target=_watch, daemon=True, name="step-watchdog").start()
    rc = proc.wait()
    return rc, state["timed_out"]


